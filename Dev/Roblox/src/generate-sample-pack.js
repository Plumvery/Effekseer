const fs = require("fs");
const path = require("path");
const { loadRocasAssetMap } = require("./cli");
const { convertProject, toLuau, writeLuauModule } = require("./converter");

const DEFAULT_OUTPUT_ROOT = "Dev/Plugin/src/ReplicatedStorage/EffekseerEffects";
const DEFAULT_ASSET_MAP = "Dev/Plugin/src/ReplicatedStorage/EffekseerAssets/Effekseer01PreviewAssetMap.luau";

function usage() {
	return `
generate-sample-pack <sample-dir> [options]

Options:
  --package-name <name>       Folder and manifest package name; default Effekseer01
  --output-root <path>        EffekseerEffects output root
  --asset-map-output <path>   Luau asset map output path
  --rocas-config <rocas.toml> Read rocas lock files and resolve assets automatically
  --rocas-sync                Run rocas sync before generating the preview pack
`.trim();
}

function parseArgs(argv) {
	const sourceDir = argv[0];
	if (!sourceDir || sourceDir === "--help" || sourceDir === "-h") {
		return { help: true };
	}

	const options = {
		sourceDir,
		packageName: "Effekseer01",
		outputRoot: DEFAULT_OUTPUT_ROOT,
		assetMapOutput: DEFAULT_ASSET_MAP,
	};

	for (let index = 1; index < argv.length; index++) {
		const arg = argv[index];
		const next = () => {
			const value = argv[++index];
			if (!value) {
				throw new Error(`Missing value for ${arg}`);
			}
			return value;
		};

		if (arg === "--package-name") {
			options.packageName = next();
		} else if (arg === "--output-root") {
			options.outputRoot = next();
		} else if (arg === "--asset-map-output") {
			options.assetMapOutput = next();
		} else if (arg === "--rocas-config" || arg === "--rocs-config") {
			options.rocasConfig = next();
		} else if (arg === "--rocas-sync" || arg === "--rocs-sync") {
			options.rocasSync = true;
		} else {
			throw new Error(`Unknown option: ${arg}\n\n${usage()}`);
		}
	}

	return options;
}

function moduleNameFor(fileName) {
	const baseName = path.basename(fileName, path.extname(fileName));
	const sanitized = baseName.replace(/[^A-Za-z0-9_]/g, "_");
	return /^[A-Za-z_]/.test(sanitized) ? sanitized : `Effect_${sanitized}`;
}

function builtInTextureFor(texturePath) {
	const name = path.basename(texturePath).toLowerCase();
	if (/(flame|fire)/.test(name)) {
		return "rbxasset://textures/particles/fire_main.dds";
	}
	if (/(cloud|smoke|wind)/.test(name)) {
		return "rbxasset://textures/particles/smoke_main.dds";
	}
	return "rbxasset://textures/particles/sparkles_main.dds";
}

function writeLuauData(data, outputPath, header) {
	const contents = [
		`-- ${header}`,
		"-- Generated by Dev/Roblox/bin/generate-sample-pack.js.",
		"-- Regenerate this file instead of editing by hand.",
		"",
		`return ${toLuau(data)}`,
		"",
	].join("\n");
	fs.mkdirSync(path.dirname(outputPath), { recursive: true });
	fs.writeFileSync(outputPath, contents);
}

function removeGeneratedModules(outputDir) {
	if (!fs.existsSync(outputDir)) {
		return;
	}
	for (const entry of fs.readdirSync(outputDir)) {
		if (entry.endsWith(".luau")) {
			fs.rmSync(path.join(outputDir, entry));
		}
	}
}

function rocasAssetIdFor(sourceDir, assetPath, rocasAssetMap) {
	if (!rocasAssetMap || !assetPath) {
		return null;
	}

	const normalizedAssetPath = assetPath.replace(/\\/g, "/");
	const absolutePath = path.resolve(sourceDir, normalizedAssetPath).replace(/\\/g, "/");
	const cwdRelativePath = path.relative(process.cwd(), absolutePath).replace(/\\/g, "/");
	return (
		rocasAssetMap.bySourcePath?.[absolutePath] ||
		rocasAssetMap.byRelativePath?.[cwdRelativePath] ||
		rocasAssetMap.byRelativePath?.[normalizedAssetPath] ||
		null
	);
}

function buildPreviewAssetMap(sourceDir, projectFiles, rocasAssetMap) {
	const assetMap = {};
	for (const projectFile of projectFiles) {
		const sourcePath = path.join(sourceDir, projectFile);
		const firstPass = convertProject(sourcePath, {
			moduleName: moduleNameFor(projectFile),
		});

		for (const texturePath of firstPass.dependencies.textures) {
			assetMap[texturePath] = rocasAssetIdFor(sourceDir, texturePath, rocasAssetMap) || builtInTextureFor(texturePath);
		}
		for (const modelPath of firstPass.dependencies.models) {
			const assetId = rocasAssetIdFor(sourceDir, modelPath, rocasAssetMap);
			if (assetId) {
				assetMap[modelPath] = assetId;
			}
		}
	}
	return assetMap;
}

async function generateSamplePack(options) {
	const sourceDir = path.resolve(options.sourceDir);
	if (!fs.existsSync(sourceDir)) {
		throw new Error(`Sample directory does not exist: ${sourceDir}`);
	}

	const projectFiles = fs
		.readdirSync(sourceDir)
		.filter((fileName) => fileName.toLowerCase().endsWith(".efkproj"))
		.sort();

	if (projectFiles.length === 0) {
		throw new Error(`No .efkproj files found in ${sourceDir}`);
	}

	const outputRoot = path.resolve(options.outputRoot);
	const outputDir = path.join(outputRoot, options.packageName);
	const assetMapOutput = path.resolve(options.assetMapOutput);
	removeGeneratedModules(outputDir);

	const rocasAssetMap = await loadRocasAssetMap(options.rocasConfig, options.rocasSync);
	const assetMap = buildPreviewAssetMap(sourceDir, projectFiles, rocasAssetMap);

	const manifest = {
		name: options.packageName,
		source: sourceDir.replace(/\\/g, "/"),
		effects: [],
	};
	const warningSummary = {};

	for (const projectFile of projectFiles) {
		const sourcePath = path.join(sourceDir, projectFile);
		const moduleName = moduleNameFor(projectFile);
		const effect = convertProject(sourcePath, {
			moduleName,
			textureMap: assetMap,
			assetMap,
			rocasAssetMap,
		});
		writeLuauModule(effect, path.join(outputDir, `${moduleName}.luau`));

		manifest.effects.push({
			name: path.basename(projectFile, path.extname(projectFile)),
			moduleName,
			source: sourcePath.replace(/\\/g, "/"),
			textures: effect.dependencies.textures,
			models: effect.dependencies.models || {},
			warnings: effect.warnings,
		});

		for (const warning of effect.warnings) {
			warningSummary[warning.code] = (warningSummary[warning.code] || 0) + 1;
		}
	}

	writeLuauData(manifest, path.join(outputRoot, `${options.packageName}Manifest.luau`), `${options.packageName} effect manifest.`);
	writeLuauData(assetMap, assetMapOutput, `${options.packageName} preview asset map.`);

	return {
		projectCount: projectFiles.length,
		outputDir,
		manifestPath: path.join(outputRoot, `${options.packageName}Manifest.luau`),
		assetMapPath: assetMapOutput,
		assetCount: Object.keys(assetMap).length,
		warningSummary,
	};
}

async function main(argv) {
	const options = parseArgs(argv);
	if (options.help) {
		console.log(usage());
		return;
	}

	const result = await generateSamplePack(options);
	console.log(`Generated ${result.projectCount} effect modules in ${result.outputDir}`);
	console.log(`Generated manifest: ${result.manifestPath}`);
	console.log(`Generated preview asset map: ${result.assetMapPath}`);
	console.log(`Preview asset mappings: ${result.assetCount}`);
	console.log(`Warnings: ${JSON.stringify(result.warningSummary)}`);
}

module.exports = {
	builtInTextureFor,
	buildPreviewAssetMap,
	generateSamplePack,
	main,
	moduleNameFor,
	parseArgs,
	rocasAssetIdFor,
};
